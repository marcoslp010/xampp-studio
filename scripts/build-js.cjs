// Small, explicit module assembler. Ships through the existing /js/app.js route
// so a UI refresh also works with a local agent that has not been restarted.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const units = [['js/shell.js', 'createShell'], ['js/dashboard.js', 'initializeDashboard']];
const bundled = units.map(([file, entry]) => {
  const source = read(file).replace(/^import \{[^}]+\} from '\.\/core\.js';\r?\n/, '').replace(`export function ${entry}`, `function ${entry}`);
  if (/^(?:import|export)\s/m.test(source)) throw new Error(`Unsupported module syntax in ${file}`);
  return `// Source: ${file}\nconst ${entry} = (() => {\n${source}\nreturn ${entry};\n})();`;
}).join('\n\n');
const app = read('src/ui/app.js')
  .replace(/^import \{ (?:createShell|initializeDashboard) \} from '[^']+';\r?\n/gm, '')
  .replaceAll("'../../js/core.js'", "'./core.js'")
  .replaceAll("'../../js/api.js'", "'./api.js'");
const marker = "const modal = $('#modal');";
if (!app.includes(marker)) throw new Error('Missing app initialization boundary');
fs.writeFileSync(path.join(root, 'js/app.js'), `// Generated by scripts/build-js.cjs. Edit src/ui/app.js, js/shell.js or js/dashboard.js.\n${app.replace(marker, () => `${bundled}\n\n${marker}`)}`);
